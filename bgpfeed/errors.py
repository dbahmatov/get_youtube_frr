"""Исключения bgpfeed.

Правило проекта: внешний сбой поднимается исключением, а не глушится
пустым списком. Пустой результат и «источник недоступен» — разные вещи,
и путать их опасно: на этом строится защита от withdraw всех маршрутов
при падении DNS.
"""


class BgpfeedError(Exception):
    """Базовое исключение. Ловится в CLI для аккуратного выхода."""


class ConfigError(BgpfeedError):
    """Конфиг невалиден. Сообщение обязано указывать конкретное поле."""


class FetchError(BgpfeedError):
    """Внешний источник (RADB, Cymru, фид) недоступен или ответил мусором."""


class AnnouncementError(BgpfeedError):
    """Сбой при работе с FRR через vtysh."""
